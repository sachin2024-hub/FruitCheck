-- FRUITCHECK - Supabase PostgreSQL schema, for a NEW project.
-- Use Supabase Authentication for credentials; do not store passwords here.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  avatar_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fruit_types (
  id integer generated by default as identity primary key,
  slug text not null unique,
  display_name text not null,
  is_active boolean not null default true,
  constraint fruit_types_slug_valid check (slug ~ '^[a-z][a-z0-9_]*$')
);

insert into public.fruit_types (slug, display_name) values
  ('apple','Apple'), ('banana','Banana'), ('mango','Mango')
on conflict (slug) do update set display_name = excluded.display_name;

create table if not exists public.model_versions (
  id uuid primary key default gen_random_uuid(),
  model_name text not null,
  version text not null,
  architecture text not null default 'MobileNetV2',
  test_accuracy numeric(6,5) check (test_accuracy between 0 and 1),
  test_sample_count integer check (test_sample_count > 0),
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  unique (model_name, version)
);

-- Set metrics only for the exact model that was evaluated.
insert into public.model_versions
  (model_name, version, architecture, test_accuracy, test_sample_count, is_active)
values ('FruitCheck CNN', '1.0.0', 'MobileNetV2', 0.97778, 360, true)
on conflict (model_name, version) do nothing;

create table if not exists public.classifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  fruit_type_id integer not null references public.fruit_types(id),
  ripeness text not null check (ripeness in ('ripe', 'unripe')),
  predicted_label text not null,
  confidence numeric(7,6) not null check (confidence >= 0 and confidence <= 1),
  image_path text,
  image_source text not null default 'gallery'
    check (image_source in ('camera', 'gallery')),
  model_version_id uuid references public.model_versions(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint label_format check (predicted_label ~ '^[a-z][a-z0-9_]*_(ripe|unripe)$')
);

create index if not exists classifications_user_date_idx
  on public.classifications(user_id, created_at desc);
create index if not exists classifications_user_fruit_idx
  on public.classifications(user_id, fruit_type_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Backfill existing accounts if any.
insert into public.profiles (id, full_name)
select id, raw_user_meta_data ->> 'full_name' from auth.users
on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.fruit_types enable row level security;
alter table public.model_versions enable row level security;
alter table public.classifications enable row level security;

-- Permissions and RLS for app users.
grant usage on schema public to authenticated;
grant select, update on public.profiles to authenticated;
grant select on public.fruit_types to authenticated;
grant select on public.model_versions to authenticated;
grant select, insert, delete on public.classifications to authenticated;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles
for select to authenticated using (id = (select auth.uid()));

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

drop policy if exists fruit_types_select on public.fruit_types;
create policy fruit_types_select on public.fruit_types
for select to authenticated using (true);

drop policy if exists model_versions_select on public.model_versions;
create policy model_versions_select on public.model_versions
for select to authenticated using (true);

drop policy if exists classifications_select_own on public.classifications;
create policy classifications_select_own on public.classifications
for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists classifications_insert_own on public.classifications;
create policy classifications_insert_own on public.classifications
for insert to authenticated with check (user_id = (select auth.uid()));

drop policy if exists classifications_delete_own on public.classifications;
create policy classifications_delete_own on public.classifications
for delete to authenticated using (user_id = (select auth.uid()));

-- Private image bucket; retain image paths, not public URLs, in the database.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fruit-images', 'fruit-images', false, 10485760,
        array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Required object key format: <auth.uid()>/<unique-image-name>.jpg
-- Storage RLS scopes access to the signed-in user's first path component.
drop policy if exists fruit_images_select_own on storage.objects;
create policy fruit_images_select_own on storage.objects
for select to authenticated
using (bucket_id = 'fruit-images' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists fruit_images_insert_own on storage.objects;
create policy fruit_images_insert_own on storage.objects
for insert to authenticated
with check (bucket_id = 'fruit-images' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists fruit_images_delete_own on storage.objects;
create policy fruit_images_delete_own on storage.objects
for delete to authenticated
using (bucket_id = 'fruit-images' and (storage.foldername(name))[1] = (select auth.uid())::text);

